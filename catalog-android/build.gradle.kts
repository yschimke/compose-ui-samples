// `:catalog-android` — the ANDROID lane of the `compose-ui-samples` catalog.
//
// Renders every AndroidX Compose sample (all but material3) through Robolectric, against AndroidX
// itself at ONE pinned androidx.dev snapshot build (`androidxSnapshotBuild` in libs.versions.toml).
// It compiles no sample sources: it depends on the `*-samples` artifacts AndroidX publishes from
// the
// same build as the libraries, so the samples and the APIs they call always match — including APIs
// newer than any release (Modifier.illuminate, aosp/4322706) and samples that need an Android `R`
// resource table, which the desktop lane cannot carry.
//
// Its only source is `AndroidSamplePreviews.kt`, generated by `scripts/android-samples.mjs`: one
// `…AndroidPreview` wrapper per renderable sample. The Design Artifacts workflow folds this module
// into the desktop catalog as `extra-module`; the distinct names make each render an ADDITION,
// which
// `scripts/samples-spec.mjs` attaches to its desktop card as a `platform: android` variant or
// publishes as an Android-only card.
//
// An application rather than a library for the reason compose-ai-tools'
// `:samples:design-catalog-m3-android` (the same kind of Android supplement to a CMP catalog) is
// one:
// the Robolectric lane renders against a merged resource APK, which an application always has.
plugins {
  alias(libs.plugins.android.application)
  alias(libs.plugins.compose.compiler)
  id("ee.schimke.composeai.preview")
}

android {
  namespace = "ee.schimke.composeuisamples.android"
  // AndroidX Compose 1.14's AAR metadata declares minCompileSdk 37.1.
  compileSdk { version = release(37) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "ee.schimke.composeuisamples.android"
    minSdk = 24
    targetSdk = 37
    versionCode = 1
    versionName = "1.0"
  }

  buildFeatures { compose = true }

  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_21
    targetCompatibility = JavaVersion.VERSION_21
  }

  testOptions { unitTests.all { it.jvmArgs("-Xmx3g") } }
}

kotlin {
  jvmToolchain(21)
  // A wrapper calling a sample that is itself marked experimental has to opt in too — the same
  // list the desktop module carries, for the same upstream APIs.
  compilerOptions {
    optIn.addAll(
      "androidx.compose.animation.ExperimentalAnimationApi",
      "androidx.compose.animation.ExperimentalSharedTransitionApi",
      "androidx.compose.animation.core.ExperimentalAnimationSpecApi",
      "androidx.compose.animation.core.ExperimentalTransitionApi",
      "androidx.compose.animation.graphics.ExperimentalAnimationGraphicsApi",
      "androidx.compose.foundation.ExperimentalFoundationApi",
      "androidx.compose.foundation.layout.ExperimentalLayoutApi",
      "androidx.compose.material.ExperimentalMaterialApi",
      "androidx.compose.runtime.ExperimentalComposeApi",
      "androidx.compose.ui.ExperimentalComposeUiApi",
      "androidx.compose.ui.text.ExperimentalTextApi",
    )
  }
}

// Every library's `androidSamples` artifact from catalog/import.json, at the pinned snapshot. Read
// from the manifest rather than repeated here, so a library added there is rendered here too.
val androidxComposeSnapshot: String = libs.versions.androidx.compose.snapshot.get()
@Suppress("UNCHECKED_CAST")
val androidSampleArtifacts: List<String> =
  ((groovy.json.JsonSlurper().parse(rootProject.file("catalog/import.json")) as Map<String, Any>)[
      "libraries"]
      as List<Map<String, Any>>)
    .mapNotNull { it["androidSamples"] as String? }

dependencies {
  androidSampleArtifacts.forEach { implementation("$it:$androidxComposeSnapshot") }
  // `androidx.compose.ui.tooling.preview.Preview` — what the generated wrappers carry.
  implementation(libs.androidx.compose.ui.tooling.preview)
  debugImplementation(libs.androidx.compose.ui.tooling)
}

// The generator's output is canonical as emitted; `--check` diffs it, so a formatter must not.
tasks.withType<com.ncorti.ktfmt.gradle.tasks.KtfmtBaseTask>().configureEach {
  exclude { it.file.name == "AndroidSamplePreviews.kt" }
}
